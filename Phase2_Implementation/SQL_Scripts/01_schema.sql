-- TRE Phase 2: the 11 Phase 1 tables and their original 63 attributes.
-- Run once in a new development database. No existing schema/data is dropped.
-- Unquoted lowercase identifiers represent the uppercase Phase 1 entity names.
BEGIN;
CREATE SCHEMA tre;
SET LOCAL search_path = tre, pg_catalog;
SET LOCAL TIME ZONE 'America/Edmonton';

CREATE TABLE client (
    client_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(80) NOT NULL CHECK (first_name = btrim(first_name) AND first_name <> ''),
    last_name varchar(80) NOT NULL CHECK (last_name = btrim(last_name) AND last_name <> ''),
    email varchar(254) UNIQUE,
    phone varchar(25) NOT NULL CHECK (btrim(phone) <> ''),
    created_at timestamptz NOT NULL DEFAULT current_timestamp CHECK (isfinite(created_at)),
    CONSTRAINT client_email_format CHECK (email IS NULL OR
        (email = lower(btrim(email)) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'))
);

CREATE TABLE agent (
    agent_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_number varchar(30) NOT NULL UNIQUE CHECK (license_number = btrim(license_number) AND license_number <> ''),
    first_name varchar(80) NOT NULL CHECK (first_name = btrim(first_name) AND first_name <> ''),
    last_name varchar(80) NOT NULL CHECK (last_name = btrim(last_name) AND last_name <> ''),
    email varchar(254) NOT NULL UNIQUE CHECK (email = lower(btrim(email)) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
    phone varchar(25) NOT NULL CHECK (btrim(phone) <> ''),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE staff (
    staff_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(80) NOT NULL CHECK (first_name = btrim(first_name) AND first_name <> ''),
    last_name varchar(80) NOT NULL CHECK (last_name = btrim(last_name) AND last_name <> ''),
    email varchar(254) NOT NULL UNIQUE CHECK (email = lower(btrim(email)) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
    role_code varchar(30) NOT NULL CHECK (role_code IN ('BROKER','ADMIN','COORDINATOR','ACCOUNTANT','MARKETING')),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE property (
    property_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_ref varchar(40) NOT NULL UNIQUE CHECK (property_ref = btrim(property_ref) AND property_ref <> ''),
    address_text varchar(200) NOT NULL CHECK (btrim(address_text) <> ''),
    municipality varchar(80) NOT NULL CHECK (btrim(municipality) <> ''),
    property_type varchar(20) NOT NULL CHECK (property_type IN ('DETACHED','CONDO','TOWNHOUSE','OTHER')),
    bedrooms smallint CHECK (bedrooms >= 0),
    bathrooms numeric(3,1) CHECK (bathrooms >= 0 AND bathrooms < 'Infinity'::numeric),
    floor_area_sqm numeric(10,2) CHECK (floor_area_sqm > 0 AND floor_area_sqm < 'Infinity'::numeric)
);

CREATE TABLE listing (
    listing_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id bigint NOT NULL REFERENCES property ON DELETE RESTRICT ON UPDATE RESTRICT,
    agent_id bigint NOT NULL REFERENCES agent ON DELETE RESTRICT ON UPDATE RESTRICT,
    asking_price numeric(12,2) NOT NULL CHECK (asking_price > 0 AND asking_price < 'Infinity'::numeric),
    listed_on date NOT NULL CHECK (isfinite(listed_on)),
    closed_on date CHECK (isfinite(closed_on)),
    status varchar(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT','ACTIVE','UNDER_OFFER','SOLD','WITHDRAWN','EXPIRED')),
    CONSTRAINT listing_dates CHECK (closed_on IS NULL OR closed_on >= listed_on),
    CONSTRAINT listing_closure_state CHECK (
        (status IN ('DRAFT','ACTIVE','UNDER_OFFER') AND closed_on IS NULL) OR
        (status IN ('SOLD','WITHDRAWN','EXPIRED') AND closed_on IS NOT NULL))
);

CREATE TABLE listing_seller (
    listing_id bigint NOT NULL REFERENCES listing ON DELETE RESTRICT ON UPDATE RESTRICT,
    client_id bigint NOT NULL REFERENCES client ON DELETE RESTRICT ON UPDATE RESTRICT,
    PRIMARY KEY (listing_id, client_id)
);

CREATE TABLE showing (
    showing_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES listing ON DELETE RESTRICT ON UPDATE RESTRICT,
    agent_id bigint NOT NULL REFERENCES agent ON DELETE RESTRICT ON UPDATE RESTRICT,
    starts_at timestamptz NOT NULL CHECK (isfinite(starts_at)),
    ends_at timestamptz NOT NULL CHECK (isfinite(ends_at)),
    status varchar(20) NOT NULL DEFAULT 'SCHEDULED'
        CHECK (status IN ('SCHEDULED','COMPLETED','CANCELLED')),
    CONSTRAINT showing_time_order CHECK (ends_at > starts_at)
);

CREATE TABLE showing_booking (
    booking_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    showing_id bigint NOT NULL REFERENCES showing ON DELETE RESTRICT ON UPDATE RESTRICT,
    client_id bigint NOT NULL REFERENCES client ON DELETE RESTRICT ON UPDATE RESTRICT,
    party_size smallint NOT NULL DEFAULT 1 CHECK (party_size BETWEEN 1 AND 3),
    status varchar(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','CONFIRMED','CANCELLED','REJECTED')),
    booked_at timestamptz NOT NULL DEFAULT current_timestamp CHECK (isfinite(booked_at))
);

CREATE TABLE offer (
    offer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES listing ON DELETE RESTRICT ON UPDATE RESTRICT,
    submitted_by_agent_id bigint NOT NULL REFERENCES agent ON DELETE RESTRICT ON UPDATE RESTRICT,
    offer_amount numeric(12,2) NOT NULL CHECK (offer_amount > 0 AND offer_amount < 'Infinity'::numeric),
    submitted_at timestamptz NOT NULL DEFAULT current_timestamp CHECK (isfinite(submitted_at)),
    expires_at timestamptz CHECK (isfinite(expires_at)),
    accepted_at timestamptz CHECK (isfinite(accepted_at)),
    status varchar(20) NOT NULL DEFAULT 'SUBMITTED'
        CHECK (status IN ('SUBMITTED','ACCEPTED','REJECTED','WITHDRAWN','EXPIRED')),
    CONSTRAINT offer_expiry_order CHECK (expires_at IS NULL OR expires_at > submitted_at),
    CONSTRAINT offer_acceptance_state CHECK (
        (status = 'ACCEPTED' AND accepted_at IS NOT NULL AND accepted_at >= submitted_at
            AND (expires_at IS NULL OR accepted_at <= expires_at)) OR
        (status <> 'ACCEPTED' AND accepted_at IS NULL))
);

CREATE TABLE offer_buyer (
    offer_id bigint NOT NULL REFERENCES offer ON DELETE RESTRICT ON UPDATE RESTRICT,
    client_id bigint NOT NULL REFERENCES client ON DELETE RESTRICT ON UPDATE RESTRICT,
    PRIMARY KEY (offer_id, client_id)
);

CREATE TABLE sale_transaction (
    sale_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id bigint NOT NULL UNIQUE REFERENCES offer ON DELETE RESTRICT ON UPDATE RESTRICT,
    coordinator_staff_id bigint NOT NULL REFERENCES staff ON DELETE RESTRICT ON UPDATE RESTRICT,
    completed_on date NOT NULL CHECK (isfinite(completed_on)),
    sale_price numeric(12,2) NOT NULL CHECK (sale_price > 0 AND sale_price < 'Infinity'::numeric)
);

COMMENT ON SCHEMA tre IS 'TotallyRealEstate Phase 2 operational data; synthetic coursework data.';
COMMENT ON TABLE staff IS '8 internal employees; independent agents are held separately in agent.';
COMMENT ON COLUMN listing.asking_price IS 'CAD asking price; not a public property assessed value.';
COMMENT ON COLUMN showing_booking.party_size IS 'Visitors including lead client, excluding agent. Capacity is three active parties, not three people.';
COMMENT ON TABLE sale_transaction IS 'Completed sale; accepted offers can exist without a completed sale.';
COMMIT;
